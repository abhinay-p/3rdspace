private func nationalCity(_ name: String, _ state: String, _ timeZoneID: String,
                          _ latitude: Double, _ longitude: Double, _ venues: [NationalVenue]) -> SampleCity {
    SampleCity(name: name, state: state, timeZoneID: timeZoneID, places: venues.enumerated().map { index, venue in
        SamplePlace(venue.name, venue.category, street: venue.street,
                    latitude + (index == 0 ? 0.002 : -0.002),
                    longitude + (index == 0 ? -0.002 : 0.002),
                    about: venue.about, events: [
                        SampleEvent(venue.eventTitle, day: (Int(abs(latitude)) + index * 3) % 10 + 1,
                                    at: index == 0 ? 10 : 18, hours: 2, capacity: 16,
                                    about: venue.eventDetails),
                    ])
    })
}

